#!/usr/bin/env bash
# Joins the numbered SQL files into ONE file (supabase/setup.sql) so it can be pasted
# into the Supabase SQL Editor in a single go.
set -euo pipefail
cd "$(dirname "$0")/../supabase"
out=setup.sql
echo "-- Mandal Masala Bhandar: complete database setup. Generated by scripts/build-setup-sql.sh. Safe to re-run." > "$out"
for f in sql/0[1-7]_*.sql; do
  printf '\n\n-- >>>>>>>>>> %s <<<<<<<<<<\n\n' "$(basename "$f")" >> "$out"
  cat "$f" >> "$out"
done
echo "Wrote supabase/$out ($(wc -l < "$out") lines)"
